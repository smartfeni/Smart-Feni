// হেল্পার: toWhatsAppNumber
// ফোন নম্বরকে WhatsApp wa.me লিংকের জন্য প্রয়োজনীয় ফুল
// ইন্টারন্যাশনাল ফরম্যাটে (কান্ট্রি কোডসহ, + ছাড়া) কনভার্ট করে।
//
// কেন দরকার: শুধু replace(/\D/g, '') দিয়ে লোকাল নম্বর
// (যেমন 01712345678) সরাসরি wa.me/ তে বসালে দেশের ভেতর থেকে
// অনেক সময় কাজ করে যায় (WhatsApp অনুমান করে নেয়), কিন্তু প্রবাসে
// থাকা কেউ ক্লিক করলে WhatsApp সেটাকে ভ্যালিড নম্বর হিসেবে চিনতে
// পারে না। তাই কান্ট্রি কোড (88) সবসময় explicit ভাবে বসানো হয়।
//
// এক জায়গায় লজিক রাখা হয়েছে যাতে ভবিষ্যতে (multi-country সাপোর্ট,
// prefilled message ইত্যাদি) বদলাতে হলে শুধু এই ফাইলটাই বদলালেই
// পুরো সাইটে কাজ হয়।
// ============================================================

export function toWhatsAppNumber(phone) {
  if (!phone) return '';

  const digits = String(phone).replace(/\D/g, '');

  if (digits.startsWith('880')) return digits;
  if (digits.startsWith('0')) return '88' + digits;
  if (digits.length === 10) return '88' + digits; // দেশের কোড ও শুরুর 0 দুটোই বাদ থাকলে

  return '88' + digits; // fallback — নিশ্চিত করে যেন কান্ট্রি কোড ছাড়া কোনো নম্বর wa.me তে না যায়
}