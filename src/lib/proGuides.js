const ROLE_ORDER = ['rider', 'instant_shop', 'shop', 'club', 'clinic'];

// বোল্ড (**...**) সহ লেখা, textContent দিয়ে (HTML নয়)
function appendRich(el, text) {
  String(text).split('**').forEach((part, i) => {
    if (!part) return;
    if (i % 2 === 1) {
      const b = document.createElement('b');
      b.textContent = part;
      el.appendChild(b);
    } else {
      el.appendChild(document.createTextNode(part));
    }
  });
}

function mk(tag, cls, text) {
  const e = document.createElement(tag);
  if (cls) e.className = cls;
  if (text != null) e.textContent = text;
  return e;
}

function renderPanel(key) {
  const g = GUIDES[key];
  const panel = mk('div', 'pg-panel');
  panel.setAttribute('role', 'tabpanel');
  (g.blocks || []).forEach((b) => {
    if (b.h) panel.appendChild(mk('h3', 'pg-h', b.h));
    if (b.p) { const p = mk('p', 'pg-p'); appendRich(p, b.p); panel.appendChild(p); }
    const items = b.ol || b.ul;
    if (items) {
      const list = mk(b.ol ? 'ol' : 'ul', 'pg-list');
      items.forEach((t) => { const li = document.createElement('li'); appendRich(li, t); list.appendChild(li); });
      panel.appendChild(list);
    }
  });
  return panel;
}

// কোন কোন রোল-ট্যাব দেখাবে ও কোনটা খোলা থাকবে
export async function resolveGuideRoles() {
  let wanted = [];
  try {
    const q = new URLSearchParams(window.location.search).get('role') || '';
    wanted = q.split(',').map((s) => s.trim()).filter((s) => GUIDES[s] && s !== 'start');
  } catch (_) { /* উপেক্ষা */ }

  let mine = [];
  try {
    const res = await getMyProRoles();
    mine = (res.roles || []).map((r) => r.role).filter((s) => GUIDES[s] && s !== 'start');
  } catch (_) { /* লগইন না থাকলে বা ব্যর্থ হলে সব রোল */ }

  let roles = mine.length ? mine.slice() : ROLE_ORDER.slice();
  wanted.forEach((w) => { if (!roles.includes(w)) roles.push(w); });
  roles = ROLE_ORDER.filter((r) => roles.includes(r));
  const active = wanted[0] || (mine.length ? mine[0] : 'start');
  return { roles, active };
}

export function renderGuide(root, { roles, active }) {
  root.textContent = '';
  const keys = ['start'].concat(roles);
  const bar = mk('div', 'pg-tabs');
  bar.setAttribute('role', 'tablist');
  const body = mk('div', 'pg-body');
  root.appendChild(bar);
  root.appendChild(body);

  function select(key) {
    bar.querySelectorAll('.pg-tab').forEach((b) => {
      const on = b.dataset.key === key;
      b.classList.toggle('active', on);
      b.setAttribute('aria-selected', on ? 'true' : 'false');
    });
    body.textContent = '';
    body.appendChild(renderPanel(key));
  }

  keys.forEach((k) => {
    const g = GUIDES[k];
    const b = mk('button', 'pg-tab');
    b.type = 'button';
    b.dataset.key = k;
    b.setAttribute('role', 'tab');
    const i = mk('i', 'fas ' + g.icon);
    b.appendChild(i);
    b.appendChild(mk('span', null, g.label));
    b.addEventListener('click', () => {
      select(k);
      try { b.scrollIntoView({ block: 'nearest', inline: 'center' }); } catch (_) { /* উপেক্ষা */ }
    });
    bar.appendChild(b);
  });

  select(keys.includes(active) ? active : 'start');
  const act = bar.querySelector('.pg-tab.active');
  if (act) { try { act.scrollIntoView({ block: 'nearest', inline: 'center' }); } catch (_) { /* উপেক্ষা */ } }
}
